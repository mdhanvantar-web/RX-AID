// ─── Central Translation Function with Fallback ─────────────────────────────
export function translate(key: string, lang: string = 'en'): string {
  const dict = TRANSLATION_REGISTRY[lang] || TRANSLATION_REGISTRY['en'];
  if (dict && dict[key]) {
    return dict[key];
  }
  // Graceful fallback to English dictionary
  if (enTranslations[key]) {
    return enTranslations[key];
  }
  return key;
}

// ─── Apply Direction and Language to HTML Root Document ─────────────────────
export function applyDocumentLanguage(langCode: string): void {
  const meta = getLanguageMeta(langCode);
  const dir = meta.direction;
  document.documentElement.lang = langCode;
  document.documentElement.dir = dir;
  if (dir === 'rtl') {
    document.documentElement.classList.add('is-rtl');
  } else {
    document.documentElement.classList.remove('is-rtl');
  }
}

// ─── Voice Speech Synthesis Utility ─────────────────────────────────────────
export function speakText(text: string, langCode: string): {
  success: boolean;
  message: string;
} {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    return { success: false, message: 'Speech synthesis is not supported on this device/browser.' };
  }

  // Cancel any ongoing speech
  window.speechSynthesis.cancel();

  const utterance = new SpeechSynthesisUtterance(text);
  const meta = getLanguageMeta(langCode);
  utterance.lang = meta.speechLocale || langCode;
  utterance.rate = 0.9; // Elderly-accessible comfortable slow pace

  // Check if voices are loaded and try to match language
  const voices = window.speechSynthesis.getVoices();
  const matchingVoice = voices.find(v => v.lang.startsWith(langCode) || v.lang.startsWith(meta.speechLocale));
  if (matchingVoice) {
    utterance.voice = matchingVoice;
  }

  window.speechSynthesis.speak(utterance);
  return { success: true, message: `Speaking in ${meta.name}` };
}

export function stopSpeaking(): void {
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    window.speechSynthesis.cancel();
  }
}

export function pauseSpeaking(): void {
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    window.speechSynthesis.pause();
  }
}

export function resumeSpeaking(): void {
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    window.speechSynthesis.resume();
  }
}

